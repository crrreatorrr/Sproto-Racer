import {readFileSync,writeFileSync} from 'node:fs';
import {concepts as track} from '../src/concepts/track.mjs';
import {concepts as terrain} from '../src/concepts/terrain.mjs';
import {concepts as oddballs} from '../src/concepts/oddballs.mjs';
import {concepts as construction} from '../src/concepts/construction.mjs';

const list=[...track,...terrain,...oddballs,...construction];
if(list.length!==36||new Set(list.map(c=>c.id)).size!==36)throw Error('Expected 36 unique concept vehicles');
const spec=list.map(({id,name,role,color,trim,bounds,wheels,hover,contactHeight})=>{
  const steering=wheels.filter(w=>w.steer);
  const front=wheels.length?Math.max(.8,...wheels.map(w=>-w.z)):1.10;
  const rear=wheels.length?Math.max(.8,...wheels.map(w=>w.z)):1.03;
  const halfTrack=wheels.length?Math.max(.4,...wheels.map(w=>Math.abs(w.x))):.8;
  return {id,name,role,color,trim,speed:1,accel:1,turn:1,bounds,
    height:contactHeight??1.50,contact:{front,rear,halfTrack},
    steering:[front+rear,Math.max(.35,...steering.map(w=>Math.abs(w.x)))],
    hover:!!hover};
});
const output="// Generated by scripts/build-concept-roster.mjs. Do not edit.\n"
  +"export const CONCEPT_CARS = [\n"+spec.map(c=>"  "+JSON.stringify(c)).join(",\n")+"\n];\n"
  +"const lookup = new Map(CONCEPT_CARS.map(car=>[car.id,car]));\n"
  +"export const conceptCarById = id => lookup.get(id);\n";
const target=new URL('../src/concept-roster.js',import.meta.url);
if(process.argv.includes('--check')){
  if(readFileSync(target,'utf8')!==output)throw Error('Concept roster differs; run node scripts/build-concept-roster.mjs');
}else writeFileSync(target,output);
