#!/usr/bin/env node
/**
 * Builds `build/racer-sim.js`, `build/racer-sim.pin.json`, and `src/sim/version.js`
 * following metaverse-hub CONTRACTS.md §2 & C12:
 * - Zero Three.js, DOM, WebGL, or timer dependencies.
 * - Lazy initialization (`__racerSim()`) so Nakama 3.41's post-InitModule deep Object.freeze
 *   freezes zero mutable caches, blueprints, or footprint tables.
 * - `--check` verifies in memory that committed files match a fresh build.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_BUNDLE = path.join(ROOT, 'build', 'racer-sim.js');
const OUT_PIN = path.join(ROOT, 'build', 'racer-sim.pin.json');
const OUT_VERSION = path.join(ROOT, 'src', 'sim', 'version.js');

const BANNED_PATTERNS = [
  [/\bTHREE\b/, 'THREE reference'],
  [/\bWebGLRenderer\b/, 'WebGLRenderer reference'],
  [/\bdocument\./, 'DOM document reference'],
  [/\bwindow\./, 'DOM window reference'],
  [/\bMath\.(sin|cos|tan|atan|atan2|exp|pow|hypot)\b/, 'Non-deterministic Math transcendental'],
];

export async function buildServerSim() {
  const result = await build({
    root: ROOT,
    configFile: false,
    logLevel: 'silent',
    build: {
      write: false,
      minify: false,
      target: 'es2020',
      lib: {
        entry: path.join(ROOT, 'src/sim/server-entry.js'),
        name: '__RacerSimInner',
        formats: ['iife'],
        fileName: () => 'racer-sim.inner.js',
      },
    },
  });

  const outputs = Array.isArray(result) ? result : [result];
  const chunk = outputs[0].output.find((o) => o.type === 'chunk');
  if (!chunk) throw new Error('Vite failed to emit server sim IIFE chunk');

  const innerCode = chunk.code.replace(/\r\n/g, '\n').trim();
  for (const [regex, label] of BANNED_PATTERNS) {
    if (regex.test(innerCode)) {
      throw new Error(`Banned pattern in server sim bundle (${label}): ${regex}`);
    }
  }

  // Wrap inside an IIFE closure so evaluating `index.js` in each Goja VM parses quickly,
  // allocates ZERO objects prior to Nakama 3.41's post-InitModule freeze, and keeps the
  // lazy singleton out of frozen globalThis properties.
  const body = [
    '// Sproto Racer server simulation bundle. Generated by scripts/build-server-sim.mjs. Do not edit.',
    'var RacerSim = (function () {',
    '  var instance = null;',
    '  function api() {',
    '    if (instance) return instance;',
    '    var fn = new Function(' + JSON.stringify(innerCode + '\nreturn __RacerSimInner;') + ');',
    '    instance = fn();',
    '    return instance;',
    '  }',
    '  return {',
    '    api: api,',
    '    version: function () { return RACER_SIM_VERSION; },',
    '    contentManifest: function () { return api().contentManifest(); },',
    '    createMatch: function (opts) { return api().createMatch(opts); },',
    '    createSimWorld: function (opts) { return api().createSimWorld(opts); },',
    '    stateHash: function (world) { return api().stateHash(world); },',
    '    captureSnapshot: function (world, ack) { return api().captureSnapshot(world, ack); },',
    '    applySnapshot: function (world, snap) { return api().applySnapshot(world, snap); },',
    '    encodeWireSnapshot: function (world, ack) { return api().encodeWireSnapshot(world, ack); },',
    '    replay: function (log) { return api().replayLog(log, RACER_SIM_VERSION); },',
    '    joinChunks: function (chunks) { return api().joinChunks(chunks); }',
    '  };',
    '})();',
    '',
  ].join('\n');

  const version = crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16);
  const bundleText = `var RACER_SIM_VERSION = '${version}';\n${body}`;
  const bundleSha256 = crypto.createHash('sha256').update(bundleText, 'utf8').digest('hex');

  // Verify inside a bare VM sandbox with Nakama-style post-init deep freeze and stripped Math transcendentals.
  const sandbox = vm.createContext({});
  vm.runInContext(
    `
    delete Math.sin; delete Math.cos; delete Math.tan;
    delete Math.atan; delete Math.atan2; delete Math.exp;
    delete Math.pow; delete Math.hypot; delete Math.random;
    `,
    sandbox,
  );
  vm.runInContext(bundleText, sandbox);
  vm.runInContext(
    `
    (function deepFreeze(obj, seen) {
      if (!obj || (typeof obj !== 'object' && typeof obj !== 'function') || seen.has(obj)) return;
      seen.add(obj);
      var names = Object.getOwnPropertyNames(obj);
      for (var i = 0; i < names.length; i++) {
        var name = names[i];
        if (name === '__racerSimInstance') continue;
        try { deepFreeze(obj[name], seen); } catch (_e) {}
      }
      if (obj !== globalThis) {
        try { Object.freeze(obj); } catch (_e) {}
      }
    })(globalThis, new Set());
    `,
    sandbox,
  );
  const manifestJson = vm.runInContext(`JSON.stringify(RacerSim.contentManifest())`, sandbox);
  const smokeHash = vm.runInContext(
    `
    (function () {
      var m = RacerSim.createMatch({ courseId: 'track01', seed: 42 });
      for (var i = 0; i < 240; i++) m.step({ 0: { throttle: 1, steer: 0.15, driftHeld: i > 190, driftPressed: i === 191 } });
      return RacerSim.stateHash(m);
    })()
    `,
    sandbox,
  );

  const contentSha256 = crypto.createHash('sha256').update(manifestJson, 'utf8').digest('hex');
  const pin = {
    game: 'sproto-racer',
    simVersion: version,
    bundleSha256,
    contentSha256,
    smokeHash240: smokeHash,
  };
  const pinText = JSON.stringify(pin, null, 2) + '\n';
  const versionText = `// Generated by scripts/build-server-sim.mjs. Do not edit.\nexport const RACER_SIM_VERSION = '${version}';\n`;

  return { version, bundleText, pinText, versionText, pin };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { version, bundleText, pinText, versionText } = await buildServerSim();
  if (process.argv.includes('--check')) {
    const haveBundle = fs.existsSync(OUT_BUNDLE) ? fs.readFileSync(OUT_BUNDLE, 'utf8') : '';
    const havePin = fs.existsSync(OUT_PIN) ? fs.readFileSync(OUT_PIN, 'utf8') : '';
    const haveVer = fs.existsSync(OUT_VERSION) ? fs.readFileSync(OUT_VERSION, 'utf8') : '';
    if (haveBundle !== bundleText || havePin !== pinText || haveVer !== versionText) {
      console.error(`Server sim bundle or pin is stale (expected ${version}). Run npm run build:server-sim.`);
      process.exit(1);
    }
    console.log(`build/racer-sim.js is up to date (version ${version}, ${bundleText.length} bytes)`);
  } else {
    fs.mkdirSync(path.dirname(OUT_BUNDLE), { recursive: true });
    fs.writeFileSync(OUT_BUNDLE, bundleText);
    fs.writeFileSync(OUT_PIN, pinText);
    fs.writeFileSync(OUT_VERSION, versionText);
    console.log(`wrote build/racer-sim.js (${bundleText.length} bytes, version ${version})`);
  }
}
