const blueprints=new Map();
export function blueprint(course){
  if(blueprints.has(course.id))return blueprints.get(course.id);
  const points=[],starts=[];
  function sector(list){
    starts.push(points.length);
    const scale=course.scale??1;
    for(const [x,n,h] of list)points.push(new THREE.Vector3(x*scale,h,-n*scale));
  }
  if(course.points)course.points.forEach(sector);else course.layout(sector);
  const curve = new THREE.CatmullRomCurve3(points, true, 'centripetal');
  const subdivisions = 24;
  const count = points.length * subdivisions;
  const nodes = [];
  let distance = 0;
  for (let i = 0; i <= count; i++) {
    const p = curve.getPoint(i / count);
    if (i > 0) distance += p.distanceTo(nodes[i - 1].p);
    nodes.push({p, s: distance});
  }
  const sections = starts.map((index, i) => ({
    name: course.names[i], start: nodes[index * subdivisions].s,
    end: i === starts.length - 1 ? distance : nodes[starts[i + 1] * subdivisions].s,
  }));
  for (let i = 0; i < count; i++) {
    const prev = nodes[THREE.MathUtils.euclideanModulo(i - 1, count)].p;
    const next = nodes[(i + 1) % count].p;
    nodes[i].f = next.clone().sub(prev).normalize();
  }
  for (let i = 0; i < count; i++) {
    const pre = nodes[THREE.MathUtils.euclideanModulo(i - 1, count)], next = nodes[(i + 1) % count];
    const rotation = Math.atan2(pre.f.x * next.f.z - pre.f.z * next.f.x, pre.f.x * next.f.x + pre.f.z * next.f.z);
    const run = pre.p.distanceTo(nodes[i].p) + nodes[i].p.distanceTo(next.p);
    nodes[i].curve = rotation / Math.max(0.01, run);
  }
  nodes[count].f = nodes[0].f;
  nodes[count].curve = nodes[0].curve;
  const result={nodes,sections,length:distance};
  blueprints.set(course.id,result);
  return result;
}

